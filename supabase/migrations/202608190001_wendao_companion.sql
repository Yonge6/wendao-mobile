create or replace function public.create_wendao_account_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.wendao_accounts (user_id)
  values (new.id)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists create_wendao_account_after_signup on auth.users;
create trigger create_wendao_account_after_signup
after insert on auth.users
for each row execute function public.create_wendao_account_for_new_user();

insert into public.wendao_accounts (user_id)
select id from auth.users
on conflict (user_id) do nothing;

