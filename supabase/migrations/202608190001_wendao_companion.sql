create table public.wendao_accounts (
  user_id uuid primary key references auth.users (id) on delete cascade,
  locale text not null default 'zh'
    check (locale in ('zh', 'en')),
  memory_enabled boolean not null default true,
  weekly_reflection_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.wendao_threads (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  title text
    check (title is null or char_length(title) between 1 and 120),
  status text not null default 'active'
    check (status in ('active', 'archived')),
  locale text not null default 'zh'
    check (locale in ('zh', 'en')),
  chapter_id integer
    check (chapter_id is null or chapter_id between 1 and 81),
  last_message_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.wendao_messages (
  id uuid primary key default gen_random_uuid(),
  thread_id uuid not null references public.wendao_threads (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  role text not null
    check (role in ('user', 'assistant')),
  content text not null
    check (char_length(content) between 1 and 12000),
  chapter_id integer
    check (chapter_id is null or chapter_id between 1 and 81),
  provider text
    check (provider is null or char_length(provider) <= 40),
  model text
    check (model is null or char_length(model) <= 80),
  request_id uuid,
  created_at timestamptz not null default now(),
  unique (user_id, request_id)
);

create table public.wendao_memories (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  source_thread_id uuid references public.wendao_threads (id) on delete set null,
  kind text not null
    check (kind in (
      'current_situation',
      'recurring_theme',
      'preference_boundary',
      'practice_outcome',
      'life_manual_context'
    )),
  summary text not null
    check (char_length(summary) between 1 and 800),
  status text not null default 'active'
    check (status in ('active', 'resolved', 'expired')),
  confidence numeric(4, 3) not null default 0.500
    check (confidence between 0 and 1),
  occurred_at timestamptz,
  expires_at timestamptz,
  last_used_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.wendao_weekly_reflections (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  week_start date not null,
  locale text not null default 'zh'
    check (locale in ('zh', 'en')),
  content text not null
    check (char_length(content) between 1 and 12000),
  chapter_ids integer[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, week_start)
);

create table public.wendao_entitlements (
  user_id uuid primary key references auth.users (id) on delete cascade,
  status text not null default 'none'
    check (status in ('none', 'active', 'grace', 'past_due', 'expired', 'revoked')),
  source text not null default 'none'
    check (source in ('none', 'apple', 'stripe', 'manual')),
  product_id text
    check (product_id is null or char_length(product_id) <= 120),
  provider_customer_id text
    check (provider_customer_id is null or char_length(provider_customer_id) <= 240),
  provider_subscription_id text
    check (provider_subscription_id is null or char_length(provider_subscription_id) <= 240),
  starts_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.wendao_usage_periods (
  user_id uuid not null references auth.users (id) on delete cascade,
  period_start date not null,
  period_end date not null,
  question_allowance integer not null
    check (question_allowance > 0),
  used_questions integer not null default 0
    check (used_questions between 0 and question_allowance),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, period_start),
  check (period_end > period_start)
);

create table public.wendao_billing_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users (id) on delete set null,
  provider text not null
    check (provider in ('apple', 'stripe')),
  provider_event_id text not null
    check (char_length(provider_event_id) between 1 and 240),
  event_type text not null
    check (char_length(event_type) between 1 and 120),
  payload_hash text not null
    check (char_length(payload_hash) between 32 and 128),
  processed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (provider, provider_event_id)
);

